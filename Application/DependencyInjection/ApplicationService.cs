using Application.Behaviors;
using Application.Mapping;
using Application.Services;
using Domain.Calculation;
using Domain.Calculation.ScoreStrategies;
using Domain.Factories;
using Domain.Interfaces;
using FluentValidation;
using Microsoft.Extensions.DependencyInjection;
using System.Reflection;
using System;
using System.Collections.Generic;
using System.Text;
using Application.Interface.IService;

namespace Application.DependencyInjection
{
    public static class ApplicationService
    {
        public static IServiceCollection AddApplicationService(this IServiceCollection services)
        {
            services.AddAutoMapper(cfg =>
            {
                cfg.AddProfile<MappingProfile>();
                cfg.AddProfile<OrganizationMappingProfile>();
            });

            services.AddMediatR(cfg =>
            {
                cfg.RegisterServicesFromAssembly(Assembly.GetExecutingAssembly());
                cfg.AddOpenBehavior(typeof(ValidationBehavior<,>));
                cfg.AddOpenBehavior(typeof(LockAuthorizationBehavior<,>));
                cfg.AddOpenBehavior(typeof(ScorecardClosureAuthorizationBehavior<,>));
            });

            services.AddValidatorsFromAssembly(Assembly.GetExecutingAssembly());

            services.AddSingleton<IFiscalCalendarService, FiscalCalendarService>();
            services.AddScoped<IPeriodLockStatusService, PeriodLockStatusService>();
            services.AddScoped<IScoreCalculationService, ScoreCalculationService>();
            services.AddScoped<IDivisionScoreCalculationService, DivisionScoreCalculationService>();
            services.AddScoped<IDivisionPeriodCalculationService, DivisionPeriodCalculationService>();
            services.AddScoped<IScorePeriodCalculationService, ScorePeriodCalculationService>();
            services.AddScoped<ScorecardClosureGuard>();
            services.AddScoped<FiscalYearLifecycleGuard>();

            // ECX business time is East Africa Time (UTC+3). Scoped so handlers, behaviors
            // and the closure job share one consistent "now" per request.
            services.AddScoped<IBusinessClock>(_ => new BusinessClock(TimeSpan.FromHours(BusinessClock.UtcOffsetHours)));

            // Request-scoped channel used to attach an override/change reason to the
            // append-only audit record generated by the persistence interceptor.
            services.AddScoped<IAuditContext, AuditContext>();

            services.AddSingleton<IScoreStrategyFactory, ScoreStrategyFactory>();
            services.AddSingleton<IKpiScoreCalculator, KpiScoreCalculator>();
            services.AddSingleton<IKraScoreCalculator, KraScoreCalculator>();
            services.AddSingleton<IGoalScoreCalculator, GoalScoreCalculator>();
            services.AddSingleton<IScorecardScoreCalculator, ScorecardScoreCalculator>();

            // FR-402/403/404: the one authoritative implementation of the initiative progress
            // and budget formulas. Registered as singletons so reports, dashboards and
            // handlers can never drift apart.
            services.AddSingleton<IInitiativeProgressCalculator, InitiativeProgressCalculator>();
            services.AddSingleton<IInitiativeBudgetCalculator, InitiativeBudgetCalculator>();

            services.AddSingleton<IFiscalPeriodIdentifierFactory, FiscalPeriodIdentifierFactory>();
            services.AddSingleton<IQuarterPeriodsStrategy, QuarterPeriodsStrategy>();

            services.AddScoped<IRagThresholdService, RagThresholdService>();
            services.AddScoped<IReportingService, ReportingService>();
            services.AddScoped<IDivisionReportService, DivisionReportService>();
            services.AddScoped<IRoleDashboardService, RoleDashboardService>();

            // Projects initiatives/milestones into DTOs using the authoritative calculators.
            services.AddScoped<Application.CQRS.Initiative.InitiativeDtoFactory>();

            // FR-401/402/403/405 shared initiative business rules.
            services.AddScoped<Application.CQRS.Initiative.InitiativeGuard>();

            return services;
        }
    }
}
